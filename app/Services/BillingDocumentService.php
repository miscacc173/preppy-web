<?php

namespace App\Services;

use App\Models\Invoice;
use App\Models\Payment;
use App\Models\PaymentRefund;
use App\Models\User;

class BillingDocumentService
{
    public function invoice(Invoice $invoice): string
    {
        $invoice->loadMissing(['items', 'payments']);
        $customer = User::find($invoice->billable_id);
        $lines = [
            'PREPPY - INVOICE',
            $invoice->invoice_number,
            '',
            'Customer: '.($customer?->name ?? 'User #'.$invoice->billable_id),
            'Email: '.($customer?->email ?? '-'),
            'Issued: '.($invoice->issued_at?->format('Y-m-d') ?? '-'),
            'Due: '.($invoice->due_at?->format('Y-m-d') ?? 'On receipt'),
            'Status: '.strtoupper($invoice->status),
            '',
            'ITEMS',
        ];
        foreach ($invoice->items as $item) {
            $adjustment = (int) data_get($item->metadata, 'amount_minor', 0);
            if (in_array(data_get($item->metadata, 'type'), ['carry_forward_credit', 'promotion_discount'], true) && $adjustment > 0) {
                $lines[] = $item->description.'  -'.$this->money($adjustment, $invoice->currency);
            } else {
                $lines[] = $item->description.' x'.$item->quantity.'  '.$this->money($item->line_total_minor, $invoice->currency);
            }
        }
        $upgradeCredit = (int) data_get($invoice->metadata, 'carry_forward_credit_minor', 0);
        $promotionDiscount = (int) data_get($invoice->metadata, 'promotion_discount_minor', 0);
        $lines[] = '';
        $lines[] = 'Subtotal: '.$this->money($invoice->subtotal_minor, $invoice->currency);
        if ($upgradeCredit > 0) $lines[] = 'Previous plan unused-value credit: -'.$this->money($upgradeCredit, $invoice->currency);
        if ($promotionDiscount > 0) $lines[] = 'Promo / discount code: -'.$this->money($promotionDiscount, $invoice->currency);
        if ($upgradeCredit === 0 && $promotionDiscount === 0) $lines[] = 'Discount: '.$this->money($invoice->discount_minor, $invoice->currency);
        $lines = [...$lines, 'Tax: '.$this->money($invoice->tax_minor, $invoice->currency), 'Total: '.$this->money($invoice->total_minor, $invoice->currency), 'Gross paid: '.$this->money($invoice->paid_minor, $invoice->currency), 'Refunded: '.$this->money($invoice->refunded_minor, $invoice->currency), 'Net paid: '.$this->money(max(0, $invoice->paid_minor - $invoice->refunded_minor), $invoice->currency), '', 'Generated by Preppy'];
        return $this->pdf($lines);
    }

    public function receipt(Payment $payment): string
    {
        $payment->loadMissing('invoice');
        return $this->pdf([
            'PREPPY - PAYMENT RECEIPT',
            $payment->receipt_number ?? 'Receipt pending',
            '',
            'Invoice: '.($payment->invoice?->invoice_number ?? '-'),
            'Provider: '.strtoupper((string) $payment->provider),
            'Provider reference: '.($payment->provider_payment_id ?? '-'),
            'Payment reference: '.$payment->checkout_reference,
            'Paid: '.$this->money($payment->amount_minor, $payment->currency),
            'Refunded: '.$this->money($payment->refunded_minor, $payment->currency),
            'Date: '.($payment->paid_at?->format('Y-m-d H:i') ?? '-'),
            'Status: '.strtoupper($payment->status),
            '',
            'Thank you for your payment.',
        ]);
    }

    public function refundReceipt(PaymentRefund $refund): string
    {
        $refund->loadMissing(['payment', 'invoice']);
        return $this->pdf([
            'PREPPY - REFUND RECEIPT',
            'Refund #'.$refund->id,
            '',
            'Invoice: '.($refund->invoice?->invoice_number ?? '-'),
            'Original receipt: '.($refund->payment?->receipt_number ?? '-'),
            'Provider refund reference: '.($refund->provider_refund_id ?? '-'),
            'Refunded: '.$this->money($refund->amount_minor, $refund->currency),
            'Reason: '.($refund->reason ?: '-'),
            'Date: '.($refund->processed_at?->format('Y-m-d H:i') ?? '-'),
            'Status: '.strtoupper($refund->status),
        ]);
    }

    private function money(int $minor, string $currency): string
    {
        return strtoupper($currency).' '.number_format($minor / 100, 2, '.', ',');
    }

    /** @param array<int, string> $lines */
    private function pdf(array $lines): string
    {
        $commands = ['BT', '/F1 11 Tf', '50 790 Td', '14 TL'];
        foreach (array_slice($lines, 0, 50) as $line) {
            $ascii = iconv('UTF-8', 'ASCII//TRANSLIT//IGNORE', (string) $line) ?: '';
            $escaped = str_replace(['\\', '(', ')'], ['\\\\', '\\(', '\\)'], $ascii);
            $commands[] = "({$escaped}) Tj";
            $commands[] = 'T*';
        }
        $commands[] = 'ET';
        $stream = implode("\n", $commands)."\n";
        $objects = [
            '<< /Type /Catalog /Pages 2 0 R >>',
            '<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
            '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 4 0 R >> >> /Contents 5 0 R >>',
            '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>',
            "<< /Length ".strlen($stream)." >>\nstream\n{$stream}endstream",
        ];
        $pdf = "%PDF-1.4\n"; $offsets = [0];
        foreach ($objects as $index => $object) {
            $offsets[] = strlen($pdf);
            $number = $index + 1;
            $pdf .= "{$number} 0 obj\n{$object}\nendobj\n";
        }
        $xref = strlen($pdf);
        $pdf .= "xref\n0 6\n0000000000 65535 f \n";
        foreach (array_slice($offsets, 1) as $offset) $pdf .= sprintf('%010d 00000 n ', $offset)."\n";
        return $pdf."trailer\n<< /Size 6 /Root 1 0 R >>\nstartxref\n{$xref}\n%%EOF\n";
    }
}
